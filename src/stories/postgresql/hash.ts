import type { StoryDef, StoryStep } from '../types'
import { PostgresqlIndexKind } from '../../postgresql/indexes'
import { Stage } from '../../core/stage'
import { Db } from '../../core/db'
import { frozeIndexAt, frozeIndexAfter } from '../stop'

const EQUAL = {
    tap: Db.Postgres,
    idx: PostgresqlIndexKind.Hash,
    subject: (s: Parameters<NonNullable<StoryStep['subject']>>[0]) => s.indexRide?.() ?? null,
} satisfies Partial<StoryStep>

const steps: StoryStep[] = [
    {
        title: 'a lookup by an exact value',
        body: 'The statement asks for a row by an exact value. It arrives through one connection into one backend, and nothing has been read. Whether this becomes a hash lookup is not the client’s decision at all — it is the planner’s, made after parsing.',
        ...EQUAL,
        dir: [0.55, 0.5, 1],
        dist: 13.0,
        fov: 40,
        send: 1,
        delay: 0,
        speed: 0.5,
        expect: (c) => c.idxStage === Stage.Socket,
        waitFor: 'the statement landing on a port',
        freezeAt: Stage.Socket,
        assert: frozeIndexAt(Stage.Socket, 'the socket it arrived on'),
    },
    {
        title: 'equality is all a hash index can answer',
        body: 'A hash index has no order inside it, so it serves equality and nothing else: no range, no ORDER BY, no prefix match. That is why a B-tree is the default and a hash index is a deliberate choice for a workload that only ever asks for one key at a time.',
        ...EQUAL,
        dir: [0.5, 0.45, 1],
        dist: 12.5,
        fov: 42,
        send: 1,
        delay: 900,
        speed: 0.45,
        expect: (c) => c.idxStage === Stage.Exec,
        waitFor: 'the executor receiving the plan',
        freezeAt: Stage.Exec,
        assert: frozeIndexAt(Stage.Exec, 'the executor'),
    },
    {
        title: 'a metapage, then one bucket',
        body: 'The hash index is a directory: a metapage that says how many buckets exist, then a page per bucket, with overflow pages chained where a bucket outgrew one. Nothing in it is sorted. The read only has to learn which single bucket can possibly hold this key.',
        ...EQUAL,
        dir: [0.5, 0.55, 1],
        dist: 7.4,
        fov: 38,
        send: 1,
        delay: 900,
        speed: 0.4,
        expect: (c) => c.idxStage === Stage.Meta && c.idxPages === 1,
        waitFor: 'the metapage',
        freezeAt: Stage.Meta,
        assert: frozeIndexAt(Stage.Meta, 'the metapage'),
    },
    {
        title: 'hash the key, read one page',
        body: 'Hashing the key selects one bucket page, and that is the entire descent: no tree to walk and no comparisons beyond the entries in that page. Fewer page reads than a B-tree is the whole reason to accept an index that can never answer a range.',
        ...EQUAL,
        dir: [0.5, 0.55, 1],
        dist: 7.0,
        fov: 36,
        send: 1,
        delay: 900,
        speed: 0.4,
        expect: (c) => c.idxStage === Stage.Bucket && c.idxPages >= 2,
        waitFor: 'the bucket the key hashed to',
        freezeAt: Stage.Bucket,
        assert: frozeIndexAfter(Stage.Bucket, 'the target bucket page', 2),
    },
    {
        title: 'a long bucket is a chain, not a tree',
        body: 'Buckets do not split the way B-tree pages do: when one fills, another page is chained to it. The worst case is therefore not a taller tree but a longer chain, and a badly hashed index can make that chain long. Here the entry sits one overflow page further on.',
        ...EQUAL,
        dir: [0.5, 0.55, 1],
        dist: 6.8,
        fov: 36,
        send: 1,
        delay: 900,
        speed: 0.4,
        expect: (c) => c.idxStage === Stage.Overflow && c.idxPages >= 3,
        waitFor: 'the overflow page in the chain',
        freezeAt: Stage.Overflow,
        assert: frozeIndexAfter(Stage.Overflow, 'the overflow page', 3),
    },
    {
        title: 'the row is still in the heap',
        body: 'The bucket holds a TID, so the row is one more page away in the heap, and cold that page comes off disk into a buffer. Three index pages and one heap page: the shortest equality lookup PostgreSQL offers — and still two files, not one.',
        ...EQUAL,
        dir: [0.45, 0.5, 1],
        dist: 7.4,
        fov: 38,
        send: 1,
        delay: 900,
        speed: 0.4,
        expect: (c) => c.idxStage === Stage.Slot && c.idxTuples === 1,
        waitFor: 'the heap page for the matched TID',
        freezeAt: Stage.Slot,
        assert: frozeIndexAt(Stage.Slot, 'the heap page in a slot'),
    },
    {
        title: 'and back out the socket',
        body: 'One row, a handful of pages, and the answer leaves through the connection it came in on. The bucket pages stay in shared_buffers, so the next equality on a neighbouring key is a memory read — which is the workload this index was chosen for.',
        ...EQUAL,
        dir: [0.55, 0.5, 1],
        dist: 13.0,
        fov: 40,
        send: 1,
        delay: 900,
        speed: 0.45,
        expect: (c) => c.idxStage === Stage.Reply,
        waitFor: 'the answer leaving the socket',
        freezeAt: Stage.Reply,
        assert: frozeIndexAt(Stage.Reply, 'the reply at the socket'),
    },
]

export const HASH_STORY: StoryDef = {
    id: 'hash-index',
    label: 'hash index lookups',
    hint: 'a directory of bucket pages: equality in three reads, and no range can ever use it',
    steps,
}
